-- Criando as tabelas

CREATE TABLE CAMPEONATO (
    ID_CAMP INTEGER GENERATED ALWAYS AS IDENTITY,
    NOME VARCHAR(50) NOT NULL,
    EDICAO INT,
    PRIMARY KEY (ID_CAMP)
);

CREATE TABLE CLUBE (
    ID_CLUBE INTEGER GENERATED ALWAYS AS IDENTITY,
    NOME VARCHAR(50) NOT NULL,
    CIDADE VARCHAR(50) NOT NULL,
    PRIMARY KEY (ID_CLUBE)
);

CREATE TABLE ESTADIO (
    ID_ESTADIO INTEGER GENERATED ALWAYS AS IDENTITY,
    NOME VARCHAR(50) NOT NULL,
    CIDADE VARCHAR(50) NOT NULL,
    CAPACIDADE INT NOT NULL,
    PRIMARY KEY (ID_ESTADIO),
    CHECK (CAPACIDADE >= 0)
);

CREATE TABLE ARBITRO (
    ID_ARB INTEGER GENERATED ALWAYS AS IDENTITY,
    PNOME VARCHAR(15) NOT NULL,
    UNOME VARCHAR(25) NOT NULL,
    DATA_NASC DATE NOT NULL,
    PRIMARY KEY (ID_ARB)
);

CREATE TABLE PARTICIPANTES (
    ID_CLUBE INT NOT NULL,
    ID_CAMP INT NOT NULL,
    PRIMARY KEY (ID_CLUBE, ID_CAMP),
    FOREIGN KEY (ID_CLUBE) REFERENCES CLUBE(ID_CLUBE) ON UPDATE CASCADE,
    FOREIGN KEY (ID_CAMP) REFERENCES CAMPEONATO(ID_CAMP) ON UPDATE CASCADE
);

CREATE TABLE EQUIPE (
    ID_EQ INTEGER GENERATED ALWAYS AS IDENTITY,
    PNOME VARCHAR(15) NOT NULL,
    UNOME VARCHAR(25) NOT NULL,
    DATA_NASC DATE NOT NULL,
    ID_CLUBE INT NOT NULL,
    FOREIGN KEY (ID_CLUBE) REFERENCES CLUBE(ID_CLUBE) ON UPDATE CASCADE,
    PRIMARY KEY (ID_EQ)
);

CREATE TABLE ATLETA (
    ID_EQ INT NOT NULL,
    POSICAO VARCHAR(20) NOT NULL,
    NUMERO_CAMISA INT NOT NULL,
    FOREIGN KEY (ID_EQ) REFERENCES EQUIPE(ID_EQ) ON UPDATE CASCADE,
    PRIMARY KEY (ID_EQ)
);

CREATE TABLE COMISSAO_TECNICA (
    ID_EQ INT NOT NULL,
    FUNCAO VARCHAR(20),
    FOREIGN KEY (ID_EQ) REFERENCES EQUIPE(ID_EQ) ON UPDATE CASCADE,
    PRIMARY KEY (ID_EQ)
);

CREATE TABLE PARTIDA (
    ID_PARTIDA INTEGER GENERATED ALWAYS AS IDENTITY,
    RODADA INT NOT NULL,
    DATA_HORA TIMESTAMP NOT NULL,
    GOLS_CASA INT NOT NULL DEFAULT 0,
    GOLS_FORA INT NOT NULL DEFAULT 0,
    STATUS VARCHAR(15) DEFAULT 'AGENDADA',
    ID_CAMP INT NOT NULL,
    ID_CLUBE_CASA INT NOT NULL,
    ID_CLUBE_FORA INT NOT NULL,
    ID_ESTADIO INT NOT NULL,
    FOREIGN KEY (ID_CAMP) REFERENCES CAMPEONATO(ID_CAMP) ON UPDATE CASCADE,
    FOREIGN KEY (ID_CLUBE_CASA) REFERENCES CLUBE(ID_CLUBE) ON UPDATE CASCADE,
    FOREIGN KEY (ID_CLUBE_FORA) REFERENCES CLUBE(ID_CLUBE) ON UPDATE CASCADE,
    FOREIGN KEY (ID_ESTADIO) REFERENCES ESTADIO(ID_ESTADIO) ON UPDATE CASCADE,
    PRIMARY KEY (ID_PARTIDA),
    CHECK (GOLS_CASA >= 0),
    CHECK (GOLS_FORA >= 0),
    CHECK (ID_CLUBE_CASA <> ID_CLUBE_FORA),
    CHECK (STATUS IN ('AGENDADA', 'EM_ANDAMENTO', 'FINALIZADA', 'ADIADA'))
);

CREATE TABLE APITA (
    ID_ARB INT NOT NULL,
    ID_PARTIDA INT NOT NULL,
    FUNCAO VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_ARB) REFERENCES ARBITRO(ID_ARB) ON UPDATE CASCADE,
    FOREIGN KEY (ID_PARTIDA) REFERENCES PARTIDA(ID_PARTIDA) ON UPDATE CASCADE,
    PRIMARY KEY (ID_ARB, ID_PARTIDA)
);

CREATE TABLE SUMULA (
    ID_SUMULA INTEGER GENERATED ALWAYS AS IDENTITY,
    TIPO_EVENTO VARCHAR(20) NOT NULL,
    MIN INT NOT NULL,
    ID_PARTIDA INT NOT NULL,
    ID_MEMBRO INT NOT NULL,
    FOREIGN KEY (ID_PARTIDA) REFERENCES PARTIDA(ID_PARTIDA) ON UPDATE CASCADE,
    FOREIGN KEY (ID_MEMBRO) REFERENCES EQUIPE(ID_EQ) ON UPDATE CASCADE,
    PRIMARY KEY (ID_SUMULA),
    CHECK (TIPO_EVENTO IN ('GOL', 'GOL_CONTRA', 'CARTAO_AMARELO', 'CARTAO_VERMELHO')),
    CHECK (MIN >= 0)
);
